-- Token diagnostics own all records; references never depend on Trace tables.
CREATE TABLE IF NOT EXISTS swe_token_runs (
  task_run_id VARCHAR(36) NOT NULL COMMENT 'Task run id',
  branch_run_id VARCHAR(36) NOT NULL COMMENT 'Branch run id',
  parent_branch_run_id VARCHAR(36) NULL COMMENT 'Parent branch run id',
  source_id VARCHAR(64) NOT NULL COMMENT 'Source id',
  tenant_id VARCHAR(128) NOT NULL COMMENT 'Tenant id',
  trace_id VARCHAR(64) NULL COMMENT 'Trace id',
  user_id VARCHAR(128) NULL COMMENT 'User id',
  agent_id VARCHAR(128) NULL COMMENT 'Agent id',
  chat_id VARCHAR(128) NULL COMMENT 'Chat id',
  session_id VARCHAR(128) NULL COMMENT 'Session id',
  role VARCHAR(128) NULL COMMENT 'Role',
  purpose VARCHAR(128) NULL COMMENT 'Purpose',
  schema_version VARCHAR(16) NULL COMMENT 'Schema version',
  telemetry_source VARCHAR(32) NULL COMMENT 'Telemetry source',
  execution_origin VARCHAR(32) NULL COMMENT 'Execution origin',
  execution_id VARCHAR(256) NULL COMMENT 'Execution id',
  identity_source VARCHAR(32) NULL COMMENT 'Identity source',
  agent_version VARCHAR(64) NULL COMMENT 'Agent version',
  phase_id VARCHAR(128) NULL COMMENT 'Phase id',
  max_input_tokens BIGINT NULL COMMENT 'Max input tokens',
  max_output_tokens BIGINT NULL COMMENT 'Max output tokens',
  compaction_epoch BIGINT NOT NULL DEFAULT 0 COMMENT 'Compaction epoch',
  gap_tracking_limited TINYINT NOT NULL DEFAULT 0 COMMENT 'Gap tracking limited',
  started_at DATETIME(6) NULL COMMENT 'Started at',
  ended_at DATETIME(6) NULL COMMENT 'Ended at',
  revision BIGINT NOT NULL DEFAULT 0 COMMENT 'Revision',
  execution_state VARCHAR(128) NOT NULL DEFAULT 'running' COMMENT 'Execution state',
  expected_attempt_count BIGINT NULL COMMENT 'Expected attempt count',
  gap_count BIGINT NOT NULL DEFAULT 0 COMMENT 'Gap count',
  data_revision BIGINT NOT NULL DEFAULT 0 COMMENT 'Data revision',
  analyzed_revision BIGINT NOT NULL DEFAULT 0 COMMENT 'Analyzed revision',
  analysis_state VARCHAR(128) NOT NULL DEFAULT 'pending' COMMENT 'Analysis state',
  dirty BIGINT NOT NULL DEFAULT 1 COMMENT 'Dirty',
  analysis_error VARCHAR(64) NULL COMMENT 'Analysis error',
  claim_token VARCHAR(128) NULL COMMENT 'Claim token',
  lease_until DATETIME(6) NULL COMMENT 'Lease until',
  PRIMARY KEY(branch_run_id),
  INDEX token_run_scope_time(source_id,tenant_id,started_at),
  INDEX token_run_task(task_run_id),
  INDEX token_run_trace(source_id,tenant_id,trace_id),
  INDEX token_run_analysis(dirty,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Runs token diagnostic records';

