-- 由环境负责人在 SWE、Scheduler、Monitor 共用的数据库中人工执行。
-- 仅新增系统任务表，不导入旧绑定，不修改旧用户任务表，不由应用自动执行。
CREATE TABLE IF NOT EXISTS swe_cron_system_jobs (
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '系统任务稳定标识',
    scope_kind VARCHAR(16) COLLATE utf8mb4_bin NOT NULL COMMENT '作用域：agent或source',
    source_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT '来源标识',
    tenant_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT '租户标识，来源级任务固定为空字符串',
    agent_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT '智能体标识，来源级任务固定为空字符串',
    task_type VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '系统任务类型：心跳、梦境、会话清理或归档',
    route_tenant_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT '调用SWE使用的路由租户，不参与来源级任务唯一身份',
    route_agent_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT 'default' COMMENT '调用SWE使用的路由智能体',
    enabled TINYINT NOT NULL DEFAULT 0 COMMENT '当前业务启用状态，关闭后禁止新的业务动作开始',
    desired_config_json LONGTEXT NOT NULL COMMENT '当前期望的安全调度配置摘要',
    effective_config_json LONGTEXT NULL COMMENT '已确认生效的安全调度配置摘要',
    previous_config_json LONGTEXT NULL COMMENT '上一有效绑定的配置摘要，用于更新交界期回调核对',
    generation BIGINT NOT NULL DEFAULT 1 COMMENT '已受理刷新意图的水位',
    sync_generation BIGINT NOT NULL DEFAULT 0 COMMENT '当前工作者领取的同步水位，不随并发刷新前移',
    synced_generation BIGINT NOT NULL DEFAULT 0 COMMENT '已确认同步完成的刷新水位',
    operation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '当前平台同步操作标识',
    effective_operation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '已生效的平台操作标识',
    previous_operation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '上一生效操作标识',
    external_job_id VARCHAR(128) NULL COMMENT '新版外部平台定时器标识，不接管旧绑定',
    sync_status VARCHAR(24) NOT NULL DEFAULT 'pending' COMMENT '同步状态：待同步、运行中、已同步或失败',
    sync_stage VARCHAR(32) NOT NULL DEFAULT 'refresh' COMMENT '当前平台同步阶段',
    sync_error_code VARCHAR(128) NULL COMMENT '安全同步错误码，不存凭据和原始响应',
    sync_owner VARCHAR(64) NULL COMMENT '当前同步工作者围栏标识',
    sync_lease_until DATETIME(6) NULL COMMENT '同步租约到期时间，UTC',
    last_request_id VARCHAR(128) NULL COMMENT '最近受理刷新请求号，用于相同请求续办',
    active_execution_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '唯一在途或待核实执行标识',
    execution_fence BIGINT NOT NULL DEFAULT 0 COMMENT '执行围栏序号，防止迟到执行覆盖新状态',
    last_status VARCHAR(24) NULL COMMENT '最近业务执行状态',
    last_run_at DATETIME(6) NULL COMMENT '最近业务开始时间，UTC',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '记录乐观锁版本',
    created_at DATETIME(6) NOT NULL COMMENT '记录创建时间，UTC',
    updated_at DATETIME(6) NOT NULL COMMENT '记录更新时间，UTC',
    PRIMARY KEY (job_id),
    UNIQUE KEY uk_system_identity (scope_kind, source_id, tenant_id, agent_id, task_type),
    KEY idx_system_sync (sync_status, sync_lease_until),
    KEY idx_system_active (active_execution_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='系统定时任务定义与平台同步状态表';

CREATE TABLE IF NOT EXISTS swe_cron_system_executions (
    execution_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '本次触发的执行标识，每次平台请求独立生成',
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '所属系统任务稳定标识',
    scope_kind VARCHAR(16) COLLATE utf8mb4_bin NOT NULL COMMENT '系统任务作用域',
    tenant_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT '逻辑租户身份，来源级任务为空字符串',
    source_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT '逻辑来源身份',
    agent_id VARCHAR(128) COLLATE utf8mb4_bin NOT NULL DEFAULT '' COMMENT '逻辑智能体身份，来源级任务为空字符串',
    task_type VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '系统任务类型',
    operation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '本次触发引用的绑定操作',
    config_generation BIGINT NOT NULL COMMENT '受理时冻结的配置水位',
    config_json LONGTEXT NOT NULL COMMENT '本次安全配置摘要，不保存凭据和任意命令',
    fence BIGINT NOT NULL COMMENT '受理时冻结的执行围栏',
    status VARCHAR(24) NOT NULL COMMENT '执行状态：已登记、已受理、运行中、成功、失败、部分成功、跳过或待核实',
    received_at DATETIME(6) NOT NULL COMMENT '回调接收时间，UTC，不冒充平台原计划时间',
    dispatch_owner VARCHAR(64) NULL COMMENT '派发租约持有者',
    dispatch_lease_until DATETIME(6) NULL COMMENT '派发租约到期时间，UTC',
    dispatch_attempt INT NOT NULL DEFAULT 0 COMMENT '同一执行身份的传输尝试次数',
    accepted_at DATETIME(6) NULL COMMENT 'SWE持久受理时间，UTC',
    run_owner VARCHAR(64) NULL COMMENT '业务执行者围栏标识',
    run_lease_until DATETIME(6) NULL COMMENT '业务执行结果核实期限，UTC',
    started_at DATETIME(6) NULL COMMENT '业务动作开始时间，UTC',
    finished_at DATETIME(6) NULL COMMENT '业务动作结束时间，UTC',
    result_json LONGTEXT NULL COMMENT '安全结果及计数，不保存完整文件内容',
    error_code VARCHAR(128) NULL COMMENT '安全执行或跳过原因码',
    resolution_request_id VARCHAR(128) NULL COMMENT '管理员核实解除的幂等请求号',
    resolved_by VARCHAR(128) NULL COMMENT '人工核实操作者',
    resolved_at DATETIME(6) NULL COMMENT '人工核实时间，UTC',
    resolution_reason VARCHAR(512) NULL COMMENT '管理员确认旧动作结束的核实原因',
    version BIGINT NOT NULL DEFAULT 1 COMMENT '执行记录乐观锁版本',
    created_at DATETIME(6) NOT NULL COMMENT '执行登记创建时间，UTC',
    updated_at DATETIME(6) NOT NULL COMMENT '执行登记更新时间，UTC',
    PRIMARY KEY (execution_id),
    KEY idx_system_execution_history (job_id, received_at, execution_id),
    KEY idx_system_execution_dispatch (status, dispatch_lease_until),
    KEY idx_system_execution_resolution (job_id, resolved_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='系统定时任务触发执行与人工核实记录表';
